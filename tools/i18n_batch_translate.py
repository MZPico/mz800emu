# ============================================================================
# PO parser (zjednodušený)
# ============================================================================

def unquote(s):
    """Odstraní uvozovky z PO řetězce."""
    s = s.strip()
    if s.startswith('"') and s.endswith('"'):
        s = s[1:-1]
    return s.replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')

def quote(s):
    """Obalí řetězec uvozovkami pro PO formát."""
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    return f'"{s}"'

class POEntry:
    def __init__(self):
        self.comments = []
        self.references = []
        self.flags = []
        self.msgctxt = ""
        self.msgid = ""
        self.msgstr = ""
        self.is_fuzzy = False

    @property
    def translated(self):
        return bool(self.msgstr) and not self.is_fuzzy

def parse_po(filepath):
    """Parsuje PO/POT soubor, vrátí (header_str, [POEntry])."""
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    blocks = re.split(r'\n\n+', content.strip())
    entries = []
    header = ""

    for block in blocks:
        entry = POEntry()
        lines = block.split('\n')
        current_key = None

        for line in lines:
            if line.startswith('#, '):
                entry.flags = line[3:].split(', ')
                entry.is_fuzzy = 'fuzzy' in entry.flags
            elif line.startswith('#: '):
                entry.references.append(line[3:])
            elif line.startswith('#'):
                entry.comments.append(line)
            elif line.startswith('msgctxt '):
                current_key = 'msgctxt'
                entry.msgctxt = unquote(line[8:])
            elif line.startswith('msgid '):
                current_key = 'msgid'
                entry.msgid = unquote(line[6:])
            elif line.startswith('msgstr '):
                current_key = 'msgstr'
                entry.msgstr = unquote(line[7:])
            elif line.startswith('"') and current_key:
                val = unquote(line)
                if current_key == 'msgctxt':
                    entry.msgctxt += val
                elif current_key == 'msgid':
                    entry.msgid += val
                elif current_key == 'msgstr':
                    entry.msgstr += val

        if entry.msgid == "" and entry.msgstr:
            header = block
        elif entry.msgid:
            entries.append(entry)

    return header, entries

def save_po(filepath, header_text, entries, lang_code, lang_name, plural_forms):
    """Uloží PO soubor."""
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        # Header
        f.write(f"# {lang_name} translation for mz800emu\n")
        f.write(f"# Copyright (C) 2026 Michal Hucik\n")
        f.write(f"# This file is distributed under the same license as the mz800emu package.\n")
        f.write(f"#\n")
        f.write('msgid ""\n')
        f.write('msgstr ""\n')
        f.write(f'"Project-Id-Version: mz800emu 1.0\\n"\n')
        f.write(f'"Report-Msgid-Bugs-To: \\n"\n')
        f.write(f'"POT-Creation-Date: 2026-03-11 21:31+0100\\n"\n')
        f.write(f'"PO-Revision-Date: 2026-03-11 22:00+0100\\n"\n')
        f.write(f'"Last-Translator: Claude Code\\n"\n')
        f.write(f'"Language-Team: {lang_name}\\n"\n')
        f.write(f'"Language: {lang_code}\\n"\n')
        f.write(f'"MIME-Version: 1.0\\n"\n')
        f.write(f'"Content-Type: text/plain; charset=UTF-8\\n"\n')
        f.write(f'"Content-Transfer-Encoding: 8bit\\n"\n')
        f.write(f'"Plural-Forms: {plural_forms}\\n"\n')
        f.write('\n')

        for entry in entries:
            for c in entry.comments:
                f.write(f"{c}\n")
            for r in entry.references:
                f.write(f"#: {r}\n")
            if entry.flags:
                f.write(f"#, {', '.join(entry.flags)}\n")
            if entry.msgctxt:
                f.write(f"msgctxt {quote(entry.msgctxt)}\n")
            f.write(f"msgid {quote(entry.msgid)}\n")
            f.write(f"msgstr {quote(entry.msgstr)}\n")
            f.write("\n")

