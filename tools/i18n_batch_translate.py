def main():
    if not os.path.exists(POT_FILE):
        print(f"CHYBA: {POT_FILE} neexistuje")
        sys.exit(1)

    _, pot_entries = parse_po(POT_FILE)
    print(f"Načteno {len(pot_entries)} záznamů z {POT_FILE}")

    for lang_code, translations in TRANSLATIONS.items():
        lang_name, plural_forms = LANG_INFO[lang_code]
        po_path = os.path.join(LOCALE_DIR, lang_code, "LC_MESSAGES", "mz800emu.po")

        # Kopie záznamů z .pot
        entries = []
        translated_count = 0
        for pe in pot_entries:
            e = POEntry()
            e.comments = pe.comments[:]
            e.references = pe.references[:]
            e.flags = pe.flags[:]
            e.msgctxt = pe.msgctxt
            e.msgid = pe.msgid
            e.msgstr = ""

            # Překlad ze slovníku
            if pe.msgid in translations:
                e.msgstr = translations[pe.msgid]
                translated_count += 1
            elif should_keep_original(pe.msgid):
                e.msgstr = pe.msgid
                translated_count += 1

            entries.append(e)

        save_po(po_path, "", entries, lang_code, lang_name, plural_forms)
        total = len(entries)
        print(f"  {lang_code} ({lang_name}): {translated_count}/{total} přeloženo -> {po_path}")

    print("\nHotovo. Spusťte 'make i18n-compile MZARCH=800' pro kompilaci .mo souborů.")

if __name__ == "__main__":
    main()
