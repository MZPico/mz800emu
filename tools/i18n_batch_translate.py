def is_format_only(s):
    """Řetězec obsahuje jen formátovací specifikátory."""
    return bool(re.match(r'^[\s%dsfu.()*:]+$', s))

def should_keep_original(msgid):
    """Řetězec se nemá překládat."""
    if msgid in TECHNICAL_STRINGS:
        return True
    if is_format_only(msgid):
        return True
    if re.match(r'^[%\s\d.():/*-]+$', msgid):
        return True
    return False

